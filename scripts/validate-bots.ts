import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { loadCatalog, type CatalogBot } from '../server/src/catalog.ts'

const write = process.argv.includes('--write')
const dir = resolve('bots')
const result = loadCatalog(dir)

if (!result.ok) {
  for (const error of result.errors) console.error(error)
  process.exit(1)
}

console.info(`Validated ${result.bots.length} bot${result.bots.length === 1 ? '' : 's'} in ${dir}`)
for (const bot of result.bots) {
  console.info(`  ${bot.slug} · ${bot.name} · ${bot.category} · ${bot.addedAt}`)
}

if (write) {
  const target = resolve('src/generated/bots.ts')
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, render(result.bots))
  console.info(`Wrote ${target}`)
}

function render(bots: CatalogBot[]): string {
  const records = bots.map((bot) => ({
    ...bot,
    kind: kindFor(bot.category),
    accent: '#111111',
  }))
  return `// Generated by npm run validate:bots -- --write. Do not edit.
export interface CatalogBot {
  slug: string
  name: string
  category: string
  integrations: string[]
  contributor: string
  addedAt: string
  grokShareUrl?: string
  summary: string
  kind: 'research' | 'writing' | 'site' | 'ops'
  accent: string
}

export const catalogBots: CatalogBot[] = ${JSON.stringify(records, null, 2)}
`
}

function kindFor(category: string): 'research' | 'writing' | 'site' | 'ops' {
  if (category === 'research' || category === 'writing' || category === 'site' || category === 'ops') return category
  return 'ops'
}
